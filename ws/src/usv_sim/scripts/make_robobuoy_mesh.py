#!/usr/bin/env python3
"""
Write the RoboBuoy's panel meshes into models/robobuoy/meshes.

panels.obj: the four white side panels and the flat top; diamonds.obj: a black diamond on
each face, 2 mm proud.

Sizes from usv_sim/robobuoy.py, so the model, the camera and this mesh agree. The model's
other parts (float frame, beacon, hat) are SDF primitives (make_course_world.py). Plain
Python, no ROS; run again after changing a size:
    python3 ws/src/usv_sim/scripts/make_robobuoy_mesh.py
"""

import math
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from usv_sim import robobuoy as rb  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'models', 'robobuoy',
                   'meshes')
PROUD = 0.002


def rot(p, k):
    """Turn a point k quarter turns about z."""
    c, s = round(math.cos(k * math.pi / 2)), round(math.sin(k * math.pi / 2))
    return (c * p[0] - s * p[1], s * p[0] + c * p[1], p[2])


def unit(v):
    n = math.sqrt(sum(c * c for c in v))
    return tuple(c / n for c in v)


def face_frame():
    """Return the +x face: bottom edge centre, up the slant, along the edge (y), normal."""
    b, t, h, z0 = rb.PANEL_BASE / 2, rb.PANEL_TOP / 2, rb.PANEL_HEIGHT, rb.PANEL_BOTTOM
    up = unit((t - b, 0.0, h))
    normal = unit((h, 0.0, b - t))
    return (b, 0.0, z0), up, (0.0, 1.0, 0.0), normal


def write_obj(path, quads, comment):
    lines = [f'# {comment}', '# GENERATED by scripts/make_robobuoy_mesh.py']
    verts, norms, faces = [], [], []
    for quad, n in quads:
        base = len(verts)
        verts += quad
        norms.append(n)
        k = len(norms)
        faces.append(f'f {base + 1}//{k} {base + 2}//{k} {base + 3}//{k}')
        faces.append(f'f {base + 1}//{k} {base + 3}//{k} {base + 4}//{k}')
    lines += [f'v {x:.5f} {y:.5f} {z:.5f}' for x, y, z in verts]
    lines += [f'vn {x:.5f} {y:.5f} {z:.5f}' for x, y, z in norms]
    lines += faces
    with open(path, 'w') as f:
        f.write('\n'.join(lines) + '\n')


def main():
    os.makedirs(OUT, exist_ok=True)
    b, t = rb.PANEL_BASE / 2, rb.PANEL_TOP / 2
    z0, z1 = rb.PANEL_BOTTOM, rb.PANEL_BOTTOM + rb.PANEL_HEIGHT
    origin, up, along, normal = face_frame()
    panels, diamonds = [], []
    for k in range(4):
        # Counter-clockwise seen from outside: bottom right, top right, top left, bottom left
        quad = [(b, -b, z0), (t, -t, z1), (t, t, z1), (b, b, z0)]
        quad = [quad[0], quad[3], quad[2], quad[1]]
        panels.append(([rot(p, k) for p in quad], rot(normal, k)))
        s0, s1 = rb.DIAMOND_START, rb.DIAMOND_START + rb.DIAMOND_LENGTH
        sm, w = (s0 + s1) / 2, rb.DIAMOND_WIDTH / 2

        def at(s, u):
            return tuple(origin[i] + s * up[i] + u * along[i] + PROUD * normal[i]
                         for i in range(3))
        d = [at(s0, 0.0), at(sm, w), at(s1, 0.0), at(sm, -w)]
        diamonds.append(([rot(p, k) for p in d], rot(normal, k)))
    panels.append(([(t, -t, z1), (t, t, z1), (-t, t, z1), (-t, -t, z1)], (0.0, 0.0, 1.0)))
    write_obj(os.path.join(OUT, 'panels.obj'), panels,
              'RoboBuoy side panels (17 x 12 in coroplast) and top, metres, z up')
    write_obj(os.path.join(OUT, 'diamonds.obj'), diamonds,
              'RoboBuoy Task 1 diamonds, one per face')
    print(f'{OUT}: panels {rb.PANEL_HEIGHT:.3f} m tall from z {z0:.3f}; top of the hat at '
          f'{rb.TOP:.3f} m')


if __name__ == '__main__':
    main()
