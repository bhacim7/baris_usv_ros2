#!/usr/bin/env python3
"""Generate a simple hull mesh (OBJ) for one catamaran hull of usv_boat.

The shape follows the team's technical drawing and photos until a CAD export (STL) is
available:
  * length 1.182 m, x from -0.591 (transom) to +0.591 (bow tip)
  * width 0.20 m aft, tapering to a point at the bow (seen from above)
  * deck at z = +0.19, flat bottom at z = -0.11 (the design draft)
  * bottom curves up to z = +0.10 at the bow ("scoop" profile seen from the side)
  * vertical transom, rounded bottom corners

Frame: hull-local, x forward, y left, z up, origin on the hull centre line at the waterline.
model.sdf places one copy at y = +0.26 and one at y = -0.26.

Usage (inside the container):
    python3 /ws/src/usv_sim/scripts/make_hull_mesh.py /ws/src/usv_sim/models/usv_boat/meshes/hull.obj
"""

import math
import os
import sys

import numpy as np

LENGTH = 1.182
X_STERN = -LENGTH / 2.0
X_BOW = LENGTH / 2.0
HALF_WIDTH = 0.10
X_TAPER_START = 0.09     # planform starts narrowing here (from the drawing's top view)
TAPER_EXPONENT = 1.6     # > 1: convex, the bow stays full before the point
MIN_HALF_WIDTH = 0.004
Z_DECK = 0.19
Z_BOTTOM = -0.11
X_SCOOP_START = 0.29     # bottom starts curving up here (from the drawing's side view)
Z_BOW_BOTTOM = 0.10      # bottom height at the bow tip
CORNER_RADIUS = 0.05
CORNER_SEGMENTS = 6
SECTIONS = 80


def half_width(x):
    if x <= X_TAPER_START:
        return HALF_WIDTH
    t = (x - X_TAPER_START) / (X_BOW - X_TAPER_START)
    return max(MIN_HALF_WIDTH, HALF_WIDTH * (1.0 - t ** TAPER_EXPONENT))


def bottom_z(x):
    if x <= X_SCOOP_START:
        return Z_BOTTOM
    t = min(1.0, (x - X_SCOOP_START) / (X_BOW - X_SCOOP_START))
    # Quarter ellipse: gentle at first, steep at the bow
    return Z_BOTTOM + (Z_BOW_BOTTOM - Z_BOTTOM) * (1.0 - math.sqrt(max(0.0, 1.0 - t * t)))


def section(x):
    """Closed loop of (y, z) points around one cross-section. Same count for every x."""
    hw = half_width(x)
    zb = bottom_z(x)
    r = min(CORNER_RADIUS, 0.9 * hw, 0.45 * (Z_DECK - zb))
    pts = [(hw, Z_DECK)]                                        # top right
    for k in range(CORNER_SEGMENTS + 1):                         # right bottom corner
        a = 0.0 - (math.pi / 2.0) * k / CORNER_SEGMENTS
        pts.append((hw - r + r * math.cos(a), zb + r + r * math.sin(a)))
    for k in range(CORNER_SEGMENTS + 1):                         # left bottom corner
        a = -math.pi / 2.0 - (math.pi / 2.0) * k / CORNER_SEGMENTS
        pts.append((-hw + r + r * math.cos(a), zb + r + r * math.sin(a)))
    pts.append((-hw, Z_DECK))                                   # top left
    return pts


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = sys.argv[1]

    # Denser sections towards the bow, where the shape changes fastest
    u = np.linspace(0.0, 1.0, SECTIONS)
    xs = X_STERN + (X_BOW - X_STERN) * (1.0 - (1.0 - u) ** 1.5)

    rings = [[(x, y, z) for (y, z) in section(x)] for x in xs]
    m = len(rings[0])
    verts = [v for ring in rings for v in ring]

    def vid(i, j):
        return i * m + (j % m)

    tris = []
    for i in range(len(rings) - 1):
        for j in range(m):
            a, b = vid(i, j), vid(i, j + 1)
            c, d = vid(i + 1, j + 1), vid(i + 1, j)
            tris += [(a, b, c), (a, c, d)]

    # End caps: fan from the section centroid
    caps = []
    for i, outward in ((0, -1.0), (len(rings) - 1, 1.0)):
        cy = sum(p[1] for p in rings[i]) / m
        cz = sum(p[2] for p in rings[i]) / m
        verts.append((xs[i], cy, cz))
        centre = len(verts) - 1
        for j in range(m):
            caps.append(((centre, vid(i, j), vid(i, j + 1)), outward))

    v = np.asarray(verts, dtype=float)

    def oriented(tri, outward_x=None):
        p0, p1, p2 = v[list(tri)]
        n = np.cross(p1 - p0, p2 - p0)
        if outward_x is not None:
            ok = n[0] * outward_x > 0
        else:
            centroid = (p0 + p1 + p2) / 3.0
            axis = np.array([centroid[0], 0.0, 0.5 * (Z_DECK + bottom_z(centroid[0]))])
            ok = np.dot(n, centroid - axis) > 0
        tri = tri if ok else (tri[0], tri[2], tri[1])
        p0, p1, p2 = v[list(tri)]
        n = np.cross(p1 - p0, p2 - p0)
        length = np.linalg.norm(n)
        return tri, (n / length if length > 1e-12 else np.array([0.0, 0.0, 1.0]))

    faces = [oriented(t) for t in tris] + [oriented(t, o) for t, o in caps]

    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, 'w') as f:
        f.write('# usv_boat hull, generated by make_hull_mesh.py\n')
        for x, y, z in verts:
            f.write(f'v {x:.5f} {y:.5f} {z:.5f}\n')
        for _, n in faces:
            f.write(f'vn {n[0]:.5f} {n[1]:.5f} {n[2]:.5f}\n')
        for k, (tri, _) in enumerate(faces, start=1):
            a, b, c = (i + 1 for i in tri)
            f.write(f'f {a}//{k} {b}//{k} {c}//{k}\n')

    print(f'{out}: {len(verts)} vertices, {len(faces)} triangles')


if __name__ == '__main__':
    main()
